def save_history(user_id, movie_title):

    with get_connection() as conn:
        conn.execute(
            """
            INSERT INTO movie_history (user_id, movie_title)
            VALUES (%s, %s)
            """,
            (int(user_id), movie_title)
        )


def get_history(user_id):

    with get_connection() as conn:
        rows = conn.execute(
            """
            SELECT movie_title, explored_at
            FROM movie_history
            WHERE user_id = %s
            ORDER BY id DESC
            LIMIT 10
            """,
            (int(user_id),)
        ).fetchall()

    return [
        {
            "title": row["movie_title"],
            "time": row["explored_at"]
        }
        for row in rows
    ]


def clear_history(user_id):

    with get_connection() as conn:
        conn.execute(
            """
            DELETE FROM movie_history
            WHERE user_id = %s
            """,
            (int(user_id),)
        )


