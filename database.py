
import os
import hashlib
import secrets
import hmac

import psycopg
from psycopg.rows import dict_row

def get_database_url():
    """Read the PostgreSQL connection string securely."""

    try:
        import streamlit as st
        database_url = st.secrets.get("DATABASE_URL")
        if database_url:
            return database_url
    except Exception:
        pass

    database_url = os.environ.get("DATABASE_URL")

    if not database_url:
        raise RuntimeError(
            "DATABASE_URL is missing. Add it to .streamlit/secrets.toml."
        )

    return database_url



def get_connection():
    """Connect to Supabase using separate connection parameters."""

    import streamlit as st

    from urllib.parse import urlsplit, unquote

    database_url = get_database_url()
    parsed = urlsplit(database_url)

    return psycopg.connect(
        host=parsed.hostname,
        port=parsed.port or 5432,
        dbname=parsed.path.lstrip("/"),
        user=unquote(parsed.username or ""),
        password=unquote(parsed.password or ""),
        row_factory=dict_row,
        connect_timeout=15
    )


# -----------------------------------------
# INITIALIZE DATABASE
# -----------------------------------------

def init_db():

    with get_connection() as conn:

        conn.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                salt TEXT NOT NULL,
                created_at TIMESTAMPTZ DEFAULT NOW()
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS movie_history (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE CASCADE,
                movie_title TEXT NOT NULL,
                explored_at TIMESTAMPTZ DEFAULT NOW()
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS movie_watchlist (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE CASCADE,
                movie_id BIGINT NOT NULL,
                movie_title TEXT NOT NULL,
                added_at TIMESTAMPTZ DEFAULT NOW(),
                UNIQUE(user_id, movie_id)
            )
        """)

        # Case-insensitive username uniqueness
        conn.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username_lower
            ON users (LOWER(username))
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_history_user
            ON movie_history(user_id, id DESC)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_watchlist_user
            ON movie_watchlist(user_id, id DESC)
        """)


# -----------------------------------------
# PASSWORD SECURITY
# -----------------------------------------

ITERATIONS = 600_000


def hash_password(password, salt):

    password_bytes = password.encode("utf-8")
    salt_bytes = bytes.fromhex(salt)

    password_hash = hashlib.pbkdf2_hmac(
        "sha256",
        password_bytes,
        salt_bytes,
        ITERATIONS
    )

    return password_hash.hex()


# -----------------------------------------
# USER REGISTRATION
# -----------------------------------------

def register_user(username, password):

    username = username.strip()

    if len(username) < 3:
        return False, "Username must contain at least 3 characters."

    if len(password) < 8:
        return False, "Password must contain at least 8 characters."

    salt = secrets.token_hex(16)
    password_hash = hash_password(password, salt)

    try:
        with get_connection() as conn:
            conn.execute(
                """
                INSERT INTO users (username, password_hash, salt)
                VALUES (%s, %s, %s)
                """,
                (username, password_hash, salt)
            )

        return True, "Account created successfully!"

    except psycopg.errors.UniqueViolation:
        return False, "This username is already taken."

    except psycopg.Error:
        return False, "A database error occurred. Please try again."


# -----------------------------------------
# USER LOGIN
# -----------------------------------------

def authenticate_user(username, password):

    username = username.strip()

    try:
        with get_connection() as conn:
            user = conn.execute(
                """
                SELECT id, username, password_hash, salt
                FROM users
                WHERE LOWER(username) = LOWER(%s)
                """,
                (username,)
            ).fetchone()

    except psycopg.Error:
        return None

    if user is None:
        return None

    entered_hash = hash_password(password, user["salt"])

    if hmac.compare_digest(
        entered_hash,
        user["password_hash"]
    ):
        return {
            "id": user["id"],
            "username": user["username"]
        }

    return None


