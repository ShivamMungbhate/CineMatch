def save_watchlist(user_id, movie_id, movie_title):

    with get_connection() as conn:
        conn.execute(
            """
            INSERT INTO movie_watchlist
                (user_id, movie_id, movie_title)
            VALUES (%s, %s, %s)
            ON CONFLICT (user_id, movie_id) DO NOTHING
            """,
            (int(user_id), int(movie_id), movie_title)
        )


def get_watchlist(user_id):

    with get_connection() as conn:
        rows = conn.execute(
            """
            SELECT movie_id, movie_title, added_at
            FROM movie_watchlist
            WHERE user_id = %s
            ORDER BY id DESC
            """,
            (int(user_id),)
        ).fetchall()

    return {
        int(row["movie_id"]): {
            "title": row["movie_title"],
            "added": row["added_at"]
        }
        for row in rows
    }


def remove_watchlist_item(user_id, movie_id):

    with get_connection() as conn:
        conn.execute(
            """
            DELETE FROM movie_watchlist
            WHERE user_id = %s AND movie_id = %s
            """,
            (int(user_id), int(movie_id))
        )


def clear_watchlist(user_id):

    with get_connection() as conn:
        conn.execute(
            """
            DELETE FROM movie_watchlist
            WHERE user_id = %s
            """,
            (int(user_id),)
        )


